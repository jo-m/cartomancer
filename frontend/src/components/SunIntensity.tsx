// scale(0.3) maps the 440px source to 132px; centre (220,220) -> (66,66).
const SUN_SIZE = 132
const SUN_CX = SUN_SIZE / 2
const SUN_CY = SUN_SIZE / 2
const DISC_R = 22

const SUN_INTENSITY_MIN = 0
const SUN_INTENSITY_MAX = 12

/** Interpolates linearly between two RGB color stops. */
function lerpRgb(
  t: number,
  a: [number, number, number],
  b: [number, number, number]
): string {
  const r = Math.round(a[0] + (b[0] - a[0]) * t)
  const g = Math.round(a[1] + (b[1] - a[1]) * t)
  const bb = Math.round(a[2] + (b[2] - a[2]) * t)
  return `rgb(${r}, ${g}, ${bb})`
}

/**
 * Returns the warm fill color for a normalised intensity t in [0, 1], ramping
 * from pale medieval gold through amber to deep crimson.
 */
function rayColor(t: number): string {
  if (t < 0.5) {
    return lerpRgb(t / 0.5, [240, 198, 110], [212, 140, 36])
  }
  return lerpRgb((t - 0.5) / 0.5, [212, 140, 36], [139, 32, 28])
}

/**
 * Formats a broadband shortwave dose in J/m^2 for compact display. Uses MJ/m^2
 * for typical ride exposures, falling back to kJ/m^2 or J/m^2 for very small
 * values.
 */
function formatDose(doseJm2: number): string {
  if (doseJm2 >= 1e6) {
    return `${(doseJm2 / 1e6).toFixed(1)} MJ/m²`
  }
  if (doseJm2 >= 1e3) {
    return `${(doseJm2 / 1e3).toFixed(0)} kJ/m²`
  }
  return `${doseJm2.toFixed(0)} J/m²`
}

interface Props {
  /** The sun intensity index in [0, 12]. */
  value: number
  /** Integrated broadband shortwave dose along the track in J/m^2. */
  doseJm2?: number
}

/**
 * SunIntensity renders a dimensionless sun intensity index in [0, 12] as a
 * medieval sun-in-splendour gauge. The 16-ray heraldic sun from sun.svg is
 * drawn at 0.3x scale; rays light up progressively (proportionally mapped from
 * the 12-step index to 16 visual rays), the numeric value is shown in the
 * central disc, and the integrated broadband shortwave dose is shown below.
 */
export default function SunIntensity({ value, doseJm2 }: Props) {
  const clamped = Math.max(
    SUN_INTENSITY_MIN,
    Math.min(SUN_INTENSITY_MAX, value)
  )
  const rounded = Math.round(clamped)

  // Proportionally map the 12-step UV index to the 16 available ray paths.
  const litRays = Math.round((rounded * RAY_COUNT) / SUN_INTENSITY_MAX)

  // Disc colour follows the current intensity.
  const discT = rounded > 0 ? (rounded - 1) / (SUN_INTENSITY_MAX - 1) : 0
  const discFill = rounded > 0 ? rayColor(discT) : "var(--color-border)"
  const discStroke =
    rounded > 0 ? rayColor(rounded / SUN_INTENSITY_MAX) : "var(--color-border)"

  return (
    <div
      className="flex items-center gap-3"
      role="img"
      aria-label={`Sun intensity ${rounded} out of ${SUN_INTENSITY_MAX}`}
    >
      <p className="text-xs font-medium text-text-muted [writing-mode:vertical-lr] rotate-180">
        Sun intensity
      </p>
      <div className="flex flex-col items-center gap-1">
        <svg
          width={SUN_SIZE}
          height={SUN_SIZE}
          viewBox={`0 0 ${SUN_SIZE} ${SUN_SIZE}`}
          overflow="visible"
        >
          {/* All 16 rays at 0.3x scale; lit rays warm-coloured, unlit muted */}
          <g transform="scale(0.3)" strokeLinejoin="round">
            {RAY_PATHS.map((d, i) => {
              const lit = i < litRays
              const fill = lit
                ? rayColor(i / (RAY_COUNT - 1))
                : "var(--color-border)"
              return (
                <path
                  key={i}
                  d={d}
                  fill={fill}
                  fillOpacity={lit ? 0.93 : 0.3}
                  stroke="none"
                />
              )
            })}
            {/* Decorative connector ring between ray bases */}
            <path
              d={RING_PATH}
              fill="none"
              stroke="var(--color-border)"
              strokeWidth={1.67}
              strokeOpacity={0.45}
            />
          </g>
          {/* Central disc carrying the numeric value */}
          <circle
            cx={SUN_CX}
            cy={SUN_CY}
            r={DISC_R}
            fill={discFill}
            fillOpacity={0.96}
            stroke={discStroke}
            strokeWidth={1.5}
          />
          <text
            x={SUN_CX}
            y={SUN_CY - 2}
            textAnchor="middle"
            dominantBaseline="central"
            fontSize={20}
            fontWeight={700}
            fill="#faf6ef"
          >
            {rounded}
          </text>
          <text
            x={SUN_CX}
            y={SUN_CY + 11}
            textAnchor="middle"
            dominantBaseline="central"
            fontSize={9}
            fill="#faf6ef"
            fillOpacity={0.85}
          >
            / {SUN_INTENSITY_MAX}
          </text>
        </svg>
        {doseJm2 != null && Number.isFinite(doseJm2) && (
          <p className="text-[10px] text-text-muted">
            Dose: {formatDose(doseJm2)}
          </p>
        )}
      </div>
    </div>
  )
}
